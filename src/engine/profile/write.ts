import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { parse, stringify } from "yaml";
import type { ExtractedProfile } from "./extract.ts";
import { configDir } from "../util.ts";

export function profilePath(): string {
  return resolve(configDir(), "profile.yaml");
}

const HEADER = (source: string, date: string) => `# Generated by JobPilot from ${source} on ${date}.
# This is your profile: user-specific input, never stored in the repository.
#
# A CV cannot tell the agent two things you must set yourself:
#   locations.allowed / locations.regions / locations.commute_max_minutes
#   comp_floor: { amount, currency, period } — or null to disable the salary filter
`;

export function renderProfileYaml(
  profile: ExtractedProfile,
  source: string,
  date: string,
): string {
  const body = {
    name: profile.name,
    email: profile.email ?? "",
    phone: profile.phone ?? "",
    cv_file: source,
    experience: {
      total_years: profile.experience.total_years,
      management_years: profile.experience.management_years,
      max_team_size: profile.experience.max_team_size ?? 0,
      employment_status: profile.experience.employment_status ?? "open_to_work",
    },
    headline: profile.headline ?? "",
    current_title: profile.current_title ?? "",
    previous_titles: profile.previous_titles,
    domains: profile.domains,
    stack: profile.stack,
    ai_practice: profile.ai_practice,
    people_management: profile.people_management,
    languages: profile.languages,
    education: profile.education ?? {},
    military: profile.military ?? {},
    citizenship: profile.citizenship,
    comp_floor: null,
    locations: {
      allowed: [],
      regions: [],
      commute_max_minutes: 60,
      remote_ok: true,
      hybrid_ok: true,
      onsite_only_ok: false,
    },
    authorization_must_pass: true,
  };

  return HEADER(source, date) + stringify(body, { lineWidth: 0 });
}

/** A profile straight from `npm run init` holds no personal data, so writing
 *  over it is safe. A real profile must never be replaced silently. */
function isTemplateProfile(path: string): boolean {
  try {
    const p = parse(readFileSync(path, "utf8")) as {
      name?: string;
      experience?: { total_years?: number };
    };
    return !p?.name || p.name === "Your Name" || !p?.experience?.total_years;
  } catch {
    return false;
  }
}

export function writeProfile(yaml: string, options: { force: boolean }): string {
  const path = profilePath();
  if (existsSync(path) && !options.force && !isTemplateProfile(path)) {
    throw new Error(
      `${path} already exists. Re-run with --force to overwrite it ` +
        "(it holds personal data, so it is never replaced silently).",
    );
  }
  writeFileSync(path, yaml, "utf8");
  return path;
}
