const raw = {
  name: "  Jane   Doe ",
  email: "jane@example.com",
  phone: "+1 555 0100",
  country: "us",
  headline: "Mobile platform leader",
  current_title: "Director of Engineering",
  previous_titles: ["Head of Mobile", "Head of Mobile", "Senior Engineer"],
  experience: { total_years: "17", management_years: 6, max_team_size: 24 },
  domains: ["mobile", "Mobile", "media & streaming"],
  stack: ["Kotlin", "Swift", "kotlin"],
  ai_practice: ["agentic workflows"],
  people_management: ["hiring and team building"],
  languages: { en: "native", HE: "fluent" },
  education: { degree: "BSc Computer Science", institution: "Example College" },
  military: { unit: "Infantry", rank: "Sergeant" },
  citizenship: ["us"],
  salary_expectation: "should be dropped",
};

test("normalizeProfile cleans, dedupes and coerces", () => {
  const p = normalizeProfile(raw)!;
  assert.equal(p.name, "Jane Doe");
  assert.equal(p.country, "US");
  assert.equal(p.experience.total_years, 17, "string years are coerced");
  assert.equal(p.experience.max_team_size, 24);
  assert.deepEqual(p.previous_titles, ["Head of Mobile", "Senior Engineer"]);
  assert.deepEqual(p.domains, ["mobile", "media & streaming"], "case-insensitive dedupe");
  assert.deepEqual(p.stack, ["Kotlin", "Swift"]);
  assert.equal(p.languages.he, "fluent");
  assert.equal(p.citizenship[0], "US");
  assert.ok(!("salary_expectation" in p), "preference fields are dropped");
});

test("normalizeProfile rejects a payload with no name", () => {
  assert.equal(normalizeProfile({ ...raw, name: "" }), null);
});

test("normalizeProfile rejects a payload with no years", () => {
  assert.equal(normalizeProfile({ ...raw, experience: {} }), null);
});

test("normalizeProfile clamps absurd values", () => {
  const p = normalizeProfile({ ...raw, experience: { total_years: 500, management_years: -3 } })!;
  assert.equal(p.experience.total_years, 60);
  assert.equal(p.experience.management_years, 0);
});

test("normalizeProfile drops empty education and military blocks", () => {
  const p = normalizeProfile({ ...raw, education: {}, military: {} })!;
  assert.equal(p.education, undefined);
  assert.equal(p.military, undefined);
});

test("renderProfileYaml produces a parseable config with the required header", () => {
  const p = normalizeProfile(raw)!;
  const yaml = renderProfileYaml(p, "cv.pdf", "2026-01-01");
  assert.ok(yaml.startsWith("# Generated by JobPilot from cv.pdf"));
  assert.ok(yaml.includes("comp_floor"));

  const parsed = parse(yaml) as Record<string, unknown>;
  assert.equal(parsed.name, "Jane Doe");
  assert.equal(parsed.comp_floor, null, "salary filter starts disabled");
  const locations = parsed.locations as Record<string, unknown>;
  assert.deepEqual(locations.allowed, []);
  assert.equal(locations.remote_ok, true);
});

test("markdown is accepted, plain text is not", async () => {
  const dir = mkdtempSync(join(tmpdir(), "jobpilot-cv-"));
  const md = join(dir, "cv.md");
  writeFileSync(md, "Jane Doe\nEngineering Manager\n", "utf8");
  assert.match(await readCv(md), /Jane Doe/);

  const txt = join(dir, "cv.txt");
  writeFileSync(txt, "Jane Doe\n", "utf8");
  await assert.rejects(() => readCv(txt), /unsupported CV format/);
});

test("readCv rejects unsupported formats", async () => {
  await assert.rejects(() => readCv("/tmp/cv.rtf"), /unsupported CV format/);
});

