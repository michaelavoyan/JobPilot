test("writeProfile may replace a template profile without --force", () => {
  const dir = mkdtempSync(join(tmpdir(), "jobpilot-cfg-"));
  const before = configDir();
  setConfigDir(dir);
  try {
    writeFileSync(profilePath(), "name: Your Name\nexperience:\n  total_years: 0\n", "utf8");
    assert.doesNotThrow(() =>
      writeProfile("name: Jane Doe\nexperience:\n  total_years: 5\n", { force: false }),
    );
    assert.match(readFileSync(profilePath(), "utf8"), /Jane Doe/);
  } finally {
    setConfigDir(before);
  }
});

test("writeProfile refuses to replace a real profile", () => {
  const dir = mkdtempSync(join(tmpdir(), "jobpilot-cfg-"));
  const before = configDir();
  setConfigDir(dir);
  try {
    writeFileSync(profilePath(), "name: Jane Doe\nexperience:\n  total_years: 5\n", "utf8");
    assert.throws(
      () => writeProfile("name: Someone Else\nexperience:\n  total_years: 1\n", { force: false }),
      /already exists/,
    );
  } finally {
    setConfigDir(before);
  }
});

function makeDocx(paragraphs: string[], file = "word/document.xml"): Buffer {
  const xml =
    '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>' +
    '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body>' +
    paragraphs.map((p) => `<w:p><w:r><w:t xml:space="preserve">${p}</w:t></w:r></w:p>`).join("") +
    "</w:body></w:document>";
  return Buffer.from(zipSync({ [file]: strToU8(xml) }));
}

const longCv = [
  "Jane Doe",
  "Engineering Manager with fifteen years of experience building mobile platforms.",
  "Led teams of eight engineers across iOS and Android, owning release and delivery.",
  "Previously staff engineer on a media streaming product used by millions of people.",
];

test("docxText turns paragraphs into lines", () => {
  const xml =
    "<w:document><w:body><w:p><w:r><w:t>Jane Doe</w:t></w:r></w:p>" +
    "<w:p><w:r><w:t>Engineering Manager</w:t></w:r></w:p></w:body></w:document>";
  assert.equal(docxText(xml), "Jane Doe\nEngineering Manager");
});

test("docxText handles tabs, breaks and entities", () => {
  const xml =
    "<w:p><w:r><w:t>Kotlin</w:t><w:tab/><w:t>Swift</w:t></w:r>" +
    "<w:r><w:br/><w:t>R&amp;D</w:t></w:r></w:p>";
  assert.equal(docxText(xml), "Kotlin\tSwift\nR&D");
});

test("readCv reads a docx", async () => {
  const dir = mkdtempSync(join(tmpdir(), "jobpilot-docx-"));
  const file = join(dir, "cv.docx");
  writeFileSync(file, makeDocx(longCv));
  const text = await readCv(file);
  assert.match(text, /Jane Doe/);
  assert.match(text, /Engineering Manager/);
});

test("readCv explains a legacy .doc", async () => {
  const dir = mkdtempSync(join(tmpdir(), "jobpilot-docx-"));
  const file = join(dir, "cv.docx");
  writeFileSync(file, makeDocx(["nothing useful"], "word/styles.xml"));
  await assert.rejects(() => readCv(file), /legacy \.doc/);
});

